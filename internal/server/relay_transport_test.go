func TestRelayRevokedIdentityCannotAuthenticateAgain(t *testing.T) {
	s, origin := relayFixture(t)
	a := newRelayUI(t, s, origin, nil)
	if e := s.relay.Unregister(a.uiID); e != nil {
		t.Fatal(e)
	}
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	ws, _, e := websocket.Dial(ctx, "ws"+strings.TrimPrefix(origin, "http")+"/v1/ws", nil)
	if e != nil {
		t.Fatal(e)
	}
	defer ws.CloseNow()
	write := func(c relayproto.Control) {
		raw, e := relayproto.EncodeControl(c)
		if e == nil {
			e = ws.Write(ctx, websocket.MessageText, raw)
		}
		if e != nil {
			t.Fatal(e)
		}
	}
	write(relayproto.Control{V: 1, Type: "ui.attach", HostID: "office"})
	_, raw, e := ws.Read(ctx)
	if e != nil {
		t.Fatal(e)
	}
	attached, e := relayproto.DecodeControl(raw)
	if e != nil {
		t.Fatal(e)
	}
	hs, init, e := relayproto.NewUIHandshake(relayproto.AuthContext{Route: relayproto.Route{Origin: origin, HostID: "office"}, Mode: "reconnect", PKH: a.transcript.PKH, PKU: a.id.PublicKey(), PairEpoch: a.transcript.PairEpoch}, a.id, nil)
	if e != nil {
		t.Fatal(e)
	}
	defer hs.Close()
	inner, e := relayproto.EncodeInner(init)
	if e != nil {
		t.Fatal(e)
	}
	write(relayproto.Control{V: 1, Type: "forward", Connection: attached.Connection, Payload: inner})
	if _, _, e := ws.Read(ctx); e == nil {
		t.Fatal("revoked identity received a new challenge")
	}
}
